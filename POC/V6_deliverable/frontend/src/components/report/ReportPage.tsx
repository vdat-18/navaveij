function formatDate(iso: string): string {
    return new Date(iso).toLocaleDateString("en-GB", {
        day: "2-digit",
        month: "long",
        year: "numeric",
    });
}

function SectionHeading({ children }: { children: React.ReactNode }) {
    return (
        <h2 className="report-section-heading text-sm font-black uppercase tracking-widest mb-4 pb-2 border-b border-[#E9ECEF]" style={{ color: "#00ABC7" }}>
            {children}
        </h2>
    );
}

function renderReasoningTrace(trace: string): React.ReactNode[] {
    const lines = trace.split('\n');
    const elements: React.ReactNode[] = [];
    let bulletBuffer: string[] = [];
    let keyCounter = 0;

    const flushBullets = () => {
        if (bulletBuffer.length === 0) return;
        const k = keyCounter++;
        elements.push(
            <ul key={`ul-${k}`} className="space-y-1.5 mb-3">
                {bulletBuffer.map((b, i) => (
                    <li key={i} className="flex items-start gap-2.5 text-sm text-[#444] leading-relaxed">
                        <span className="mt-[7px] w-1.5 h-1.5 rounded-full shrink-0 bg-[#00ABC7]/50" />
                        <span>{b}</span>
                    </li>
                ))}
            </ul>
        );
        bulletBuffer = [];
    };

    for (const raw of lines) {
        const line = raw.trim();
        if (!line) { flushBullets(); continue; }

        const isBullet = /^[-•*]\s+/.test(line);
        const isHeader = !isBullet && line.endsWith(':') && line.length < 72;

        if (isBullet) {
            bulletBuffer.push(line.replace(/^[-•*]\s+/, ''));
            continue;
        }

        flushBullets();
        const k = keyCounter++;

        if (isHeader) {
            elements.push(
                <p key={k} className="text-[10px] font-black uppercase tracking-widest text-[#00ABC7] mt-4 mb-1.5 first:mt-0">
                    {line.slice(0, -1)}
                </p>
            );
        } else {
            elements.push(
                <p key={k} className="text-sm text-[#444] leading-relaxed mb-2 last:mb-0">
                    {line}
                </p>
            );
        }
    }

    flushBullets();
    return elements;
}

